export function t(key: string, lang: Lang, vars?: Record<string, string>): string {
  const text = translations[lang]?.[key] ?? translations.en[key] ?? key;
  if (!vars) return text;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replace(`{${k}}`, v), text);
}